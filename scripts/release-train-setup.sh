#!/usr/bin/env bash
# release-train-setup.sh — one-time activation for the weekly staging release train (#2205).
# SAFE to re-run (idempotent). Like local-deploy-setup.sh this is the ONLY step with real
# side-effects (it installs + starts a user systemd timer), so it is never run by the test suite.
#
#   bash scripts/release-train-setup.sh            # generate the env file, install, enable the timer
#   bash scripts/release-train-setup.sh --verify    # verify only: no install, no enable, no start
#
# What it does:
#   1. Generates ~/.config/skillforge/release-train.env (mode 0600) from the values currently
#      exported in YOUR shell. This is the whole point of the exercise: EXPO_ASC_API_KEY_PATH,
#      EXPO_ASC_KEY_ID, EXPO_ASC_ISSUER_ID, EXPO_APPLE_TEAM_ID and EXPO_TOKEN live in ~/.bashrc,
#      and systemd does not source ~/.bashrc — a timer would see none of them. The file is NOT in
#      the repo (it holds credentials); the units reference it with `EnvironmentFile=-`.
#   2. Installs the three units under ~/.config/systemd/user/, rewriting WorkingDirectory and
#      ExecStart to THIS checkout so the committed units aren't machine-locked.
#   3. Runs `systemd-analyze verify` on all three and prints the next elapse.
#
# It deliberately does NOT start skillforge-release-train.service — starting it cuts a real
# staging release. Use skillforge-release-train-checkenv.service to prove the environment.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UNIT_DIR="$HOME/.config/systemd/user"
ENV_DIR="$HOME/.config/skillforge"
ENV_FILE="$ENV_DIR/release-train.env"
UNITS=(skillforge-release-train.service skillforge-release-train.timer skillforge-release-train-checkenv.service)

VERIFY_ONLY=0
[[ "${1:-}" == "--verify" ]] && VERIFY_ONLY=1

ok()   { printf '\033[32m✓ %s\033[0m\n' "$*"; }
warn() { printf '\033[33m! %s\033[0m\n' "$*"; }

# ── 1. The environment file ───────────────────────────────────────────────────
# Every variable the mobile half needs, plus PATH additions systemd cannot infer.
ENV_VARS=(EXPO_ASC_API_KEY_PATH EXPO_ASC_KEY_ID EXPO_ASC_ISSUER_ID EXPO_APPLE_TEAM_ID EXPO_TOKEN)

if [[ "$VERIFY_ONLY" -eq 0 ]]; then
  echo "1) Generating $ENV_FILE from your current shell environment…"
  mkdir -p "$ENV_DIR"
  umask 077
  {
    echo "# Generated by scripts/release-train-setup.sh — DO NOT COMMIT (holds credentials)."
    echo "# Regenerate after rotating any Apple/Expo credential:  bash scripts/release-train-setup.sh"
    for v in "${ENV_VARS[@]}"; do
      if [[ -n "${!v:-}" ]]; then
        printf '%s=%s\n' "$v" "${!v}"
      else
        printf '# %s=   # UNSET in the shell that ran this setup — the mobile phase will refuse to start\n' "$v"
      fi
    done
  } > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  ok "wrote $ENV_FILE (0600)"
fi

missing=()
for v in "${ENV_VARS[@]}"; do [[ -n "${!v:-}" ]] || missing+=("$v"); done
if [[ "${#missing[@]}" -gt 0 ]]; then
  warn "not set in this shell (the mobile phase will fail its preflight until they are):"
  printf '    - %s\n' "${missing[@]}"
  echo "    Export them (see ~/.bashrc and docs/49-mobile-store-submission.md), then re-run this script."
fi

# ── 2. Install the units ──────────────────────────────────────────────────────
if [[ "$VERIFY_ONLY" -eq 0 ]]; then
  echo "2) Installing the user systemd units…"
  mkdir -p "$UNIT_DIR"
  for u in "${UNITS[@]}"; do
    sed -e "s|^WorkingDirectory=.*|WorkingDirectory=${ROOT}|" \
        -e "s|\(ExecStart=/usr/bin/env bash \)[^ ]*/scripts/release-train.sh|\1${ROOT}/scripts/release-train.sh|" \
        "$ROOT/deploy/systemd/$u" > "$UNIT_DIR/$u"
  done
  systemctl --user daemon-reload
  ok "installed: ${UNITS[*]}"
fi

# ── 3. Verify ─────────────────────────────────────────────────────────────────
echo "3) Verifying the units…"
verify_src_dir="$UNIT_DIR"
[[ "$VERIFY_ONLY" -eq 1 && ! -f "$UNIT_DIR/${UNITS[0]}" ]] && verify_src_dir="$ROOT/deploy/systemd"
vrc=0
for u in "${UNITS[@]}"; do
  systemd-analyze --user verify "$verify_src_dir/$u" 2>&1 | grep -v '^$' || true
  systemd-analyze --user verify "$verify_src_dir/$u" >/dev/null 2>&1 || vrc=1
done
[[ "$vrc" -eq 0 ]] && ok "systemd-analyze verify: clean" || warn "systemd-analyze verify reported issues (see above)"

if [[ "$VERIFY_ONLY" -eq 1 ]]; then
  echo "  (--verify: nothing installed, enabled, or started)"
  exit "$vrc"
fi

echo "4) Enabling the weekly timer (Fri 20:00, Persistent=true)…"
systemctl --user enable --now skillforge-release-train.timer
loginctl enable-linger "$USER" 2>/dev/null || warn "could not enable linger — run: sudo loginctl enable-linger $USER"
systemctl --user list-timers skillforge-release-train.timer --no-pager || true

cat <<EOF

✅ The release train is armed (Fri 20:00, Persistent=true — a missed Friday fires on resume).

Prove the unit's environment WITHOUT cutting anything:
   systemctl --user start skillforge-release-train-checkenv.service
   journalctl --user -u skillforge-release-train-checkenv.service -n 40 --no-pager

Dry-run the whole plan by hand:
   bash scripts/release-train.sh --dry-run

Status / logs:
   systemctl --user list-timers skillforge-release-train.timer
   journalctl --user -u skillforge-release-train.service -f     (+ /tmp/release-train-<run-id>/)

Disarm:  systemctl --user disable --now skillforge-release-train.timer
EOF
