"""Iteration bookkeeping, ported off the shell (#109)."""

from __future__ import annotations

import subprocess
from pathlib import Path

from ai_harness.kernel.clock import FrozenClock
from ai_harness.kernel.outcome import ErrorCategory
from ai_harness.product.iterations import Iterations
from ai_harness.product.state import ProductState

SHELL_INDEX = """\
# Iteration Log

> ⚠️ **This file is auto-generated** from `docs/iterations/` by
> `agent iteration index`. Do NOT hand-edit it.
> To add an iteration, create a new file under `docs/iterations/`
> following the naming convention in `CLAUDE.md`.

**Total iterations:** 3

---

- [Iteration 10](iterations/010-tenth.md) — 2026-03-02
- [Iteration 2](iterations/002-second.md) — 2026-02-11 — pricing
- [Iteration 1](iterations/001-first.md) — 2026-01-05 — the wedge

---

*Generated 2026-01-01T00:00:00Z. 3 iterations.*
"""
"""Produced by running `scripts/generate-iteration-index.sh` on the corpus below and freezing the
timestamp. One line differs deliberately: the "generated by" pointer names the command that
regenerates it, which after the port is `agent iteration index`."""


def _corpus(tmp_path: Path) -> Iterations:
    directory = tmp_path / "docs/iterations"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "001-first.md").write_text("## Iteration 1 — 2026-01-05 — the wedge\nbody\n")
    (directory / "002-second.md").write_text("## Iteration 2 — 2026-02-11 — pricing\nbody\n")
    (directory / "010-tenth.md").write_text("## Iteration 10 — 2026-03-02\nbody\n")
    return Iterations(
        directory=directory,
        index_file=tmp_path / "docs/06-iteration-log.md",
        clock=FrozenClock(),
    )


# ── the index ────────────────────────────────────────────────────────────────────


def test_the_index_matches_the_shell_byte_for_byte(tmp_path):
    assert _corpus(tmp_path).render_index() == SHELL_INDEX


def test_iterations_are_listed_newest_first_with_leading_zeros_stripped(tmp_path):
    iterations = _corpus(tmp_path)
    assert [item.number for item in iterations.load()] == [10, 2, 1]
    # `010-tenth.md` is iteration 10, not 010 — the display number strips the padding.
    assert "Iteration 10]" in iterations.render_index()


def test_a_header_without_a_description_still_produces_a_title(tmp_path):
    items = {item.number: item for item in _corpus(tmp_path).load()}
    assert items[10].title == "2026-03-02"
    assert items[2].title == "2026-02-11 — pricing"


def test_a_file_that_breaks_the_convention_is_reported_rather_than_skipped(tmp_path):
    iterations = _corpus(tmp_path)
    (iterations.directory / "notes.md").write_text("## Not an iteration\n")

    rendered = iterations.render_index()
    assert "notes.md" not in rendered
    # Silently skipping it is how an iteration goes missing from the index.
    assert any("no NNN- prefix" in note for note in iterations.notes)


def test_an_empty_corpus_produces_a_valid_index(tmp_path):
    directory = tmp_path / "docs/iterations"
    directory.mkdir(parents=True)
    rendered = Iterations(directory=directory, clock=FrozenClock()).render_index()
    assert "**Total iterations:** 0" in rendered
    assert "0 iterations." in rendered


def test_where_the_iterations_live_is_configuration_not_a_constant(tmp_path):
    """Q2: a package that names one project's doc layout has assumed the repository it was
    supposed to be able to target. The header interpolates the configured directory."""
    directory = tmp_path / "notes/rounds"
    directory.mkdir(parents=True)
    (directory / "001-x.md").write_text("## Iteration 1 — 2026-01-05\n")

    rendered = Iterations(directory=directory, clock=FrozenClock()).render_index()
    assert "from `notes/rounds/`" in rendered
    assert "docs/iterations" not in rendered


def test_a_repository_that_keeps_no_index_is_a_normal_repository(tmp_path):
    from ai_harness.schemas.profile import RepoProfile

    # Unset by default: the numbered-document layout is one project's convention.
    assert RepoProfile().iteration_index == ""
    assert RepoProfile().iterations_dir == "docs/iterations"

    iterations = Iterations(directory=tmp_path / "docs/iterations", clock=FrozenClock())
    assert iterations.index_file is None


def test_write_index_is_a_pure_function_of_the_corpus(tmp_path):
    iterations = _corpus(tmp_path)
    first = iterations.write_index().read_text()
    second = iterations.write_index().read_text()
    assert first == second


# ── the count ────────────────────────────────────────────────────────────────────


def test_the_count_migrates_from_the_filenames_once_then_reads_the_state(tmp_path):
    state = ProductState(directory=tmp_path / "state", clock=FrozenClock())
    state.init("x")
    iterations = _corpus(tmp_path)
    iterations.state = state

    # Never stored: derive it from the corpus and persist, so the next read is O(1) rather than
    # a glob and a sort over a directory that only grows.
    assert iterations.current() == 10
    assert state.get(".iteration_count") == 10

    # Now stored, and authoritative even if the corpus changes underneath.
    (iterations.directory / "011-eleventh.md").write_text("## Iteration 11 — 2026-04-01\n")
    assert iterations.current() == 10


def test_peek_does_not_claim_and_next_does(tmp_path):
    state = ProductState(directory=tmp_path / "state", clock=FrozenClock())
    state.init("x")
    iterations = _corpus(tmp_path)
    iterations.state = state

    assert iterations.peek_next() == 11
    assert iterations.peek_next() == 11  # peeking twice gives the same answer
    assert iterations.take_next() == 11
    assert iterations.current() == 11
    assert iterations.peek_next() == 12


# ── immutability ─────────────────────────────────────────────────────────────────


def _git(tmp_path: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=tmp_path, check=True, capture_output=True)


def test_modifying_a_past_iteration_is_a_policy_failure_naming_the_file(tmp_path):
    _git(tmp_path, "init", "-q", "-b", "main")
    _git(tmp_path, "config", "user.email", "t@example.com")
    _git(tmp_path, "config", "user.name", "t")
    iterations = _corpus(tmp_path)
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-qm", "iterations")
    _git(tmp_path, "checkout", "-q", "-b", "branch")

    assert iterations.check_immutable("main", root=tmp_path).is_ok

    (iterations.directory / "001-first.md").write_text("## Iteration 1 — rewritten\n")
    _git(tmp_path, "commit", "-qam", "rewrite history")

    outcome = iterations.check_immutable("main", root=tmp_path)
    assert outcome.category is ErrorCategory.POLICY
    error = outcome.error
    assert error is not None
    assert any("001-first.md" in line for line in error.details["violations"])
    # An iteration records what was tried; rewriting it loses the ability to tell what was tried.
    assert "what was tried" in (error.remedy or "")


def test_adding_an_iteration_is_not_a_violation(tmp_path):
    _git(tmp_path, "init", "-q", "-b", "main")
    _git(tmp_path, "config", "user.email", "t@example.com")
    _git(tmp_path, "config", "user.name", "t")
    iterations = _corpus(tmp_path)
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-qm", "iterations")
    _git(tmp_path, "checkout", "-q", "-b", "branch")

    (iterations.directory / "011-new.md").write_text("## Iteration 11 — 2026-04-01\n")
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-qm", "add an iteration")

    assert iterations.check_immutable("main", root=tmp_path).is_ok


def test_no_iterations_directory_is_not_a_failure(tmp_path):
    assert Iterations(directory=tmp_path / "nowhere").check_immutable("main", root=tmp_path).is_ok
